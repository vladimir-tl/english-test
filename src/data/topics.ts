import type { Lang } from '../i18n/ui';

export type TopicLevel = 'A2' | 'B1';
type Text = Record<Lang, string>;

export interface TopicQuestion {
  prompt: string;
  /** four options */
  options: string[];
  /** index of the correct option */
  answer: number;
  /** short explanation shown after the answer */
  explain: string;
}

/** [English term, Russian, Estonian, simple English definition] */
export type Word = [string, string, string, string];

export interface Topic {
  slug: string;
  level: TopicLevel;
  title: Text;
  /** key phrases shown on the card */
  phrases: string;
  words: Word[];
  questions: TopicQuestion[];
}

export interface Module {
  id: string;
  title: Text;
  goal: Text;
  /** general introductory module: shown first and without a number */
  intro?: boolean;
  topics: Topic[];
}

/** Multiple choice with the correct option written first; the quiz shuffles options on screen. */
const q = (prompt: string, options: [string, string, string, string], explain: string): TopicQuestion => ({
  prompt,
  options,
  answer: 0,
  explain,
});

